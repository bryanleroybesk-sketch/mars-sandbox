--[[
	RbxCharacterSounds  (LocalScript in StarterPlayer/StarterPlayerScripts)

	A LocalScript with this exact name REPLACES Roblox's default character
	sounds script. We do this on purpose: the default footsteps would play
	even while crouching. Footsteps and rustling are made by the server
	instead (MovementService), based on your stance.

	Leave this script empty.
]]
